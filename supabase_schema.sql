-- 1. ENQUIRIES TABLE
CREATE TABLE IF NOT EXISTS public.enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    product TEXT DEFAULT 'General Steel Inquiry',
    message TEXT,
    status TEXT DEFAULT 'pending',
    source TEXT DEFAULT 'website',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. ORDERS / SHIPMENTS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number TEXT UNIQUE NOT NULL,
    client_name TEXT NOT NULL,
    phone TEXT,
    product TEXT NOT NULL,
    quantity_metric_tons NUMERIC DEFAULT 10,
    delivery_destination TEXT,
    stage TEXT DEFAULT 'RFQ Received',
    estimated_delivery_date TEXT,
    vehicle_number TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. PRODUCTS CATALOG TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    grade TEXT,
    description TEXT,
    specs TEXT,
    badge TEXT,
    image_url TEXT,
    tags TEXT[],
    estimated_price_per_ton NUMERIC DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Allow Public Anon Access (Read/Insert for Enquiries, Full Access with Anon Key for Admin)
-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Public can insert enquiries" ON public.enquiries;
DROP POLICY IF EXISTS "Public can view enquiries" ON public.enquiries;
DROP POLICY IF EXISTS "Public can update enquiries" ON public.enquiries;
DROP POLICY IF EXISTS "Public can delete enquiries" ON public.enquiries;

CREATE POLICY "Public can insert enquiries" ON public.enquiries FOR INSERT WITH CHECK (true);
CREATE POLICY "Public can view enquiries" ON public.enquiries FOR SELECT USING (true);
CREATE POLICY "Public can update enquiries" ON public.enquiries FOR UPDATE USING (true);
CREATE POLICY "Public can delete enquiries" ON public.enquiries FOR DELETE USING (true);

DROP POLICY IF EXISTS "Public can access orders" ON public.orders;
CREATE POLICY "Public can access orders" ON public.orders FOR ALL USING (true);

DROP POLICY IF EXISTS "Public can access products" ON public.products;
CREATE POLICY "Public can access products" ON public.products FOR ALL USING (true);

